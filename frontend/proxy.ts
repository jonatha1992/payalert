import { createServerClient, type CookieOptions } from '@supabase/ssr'
import { NextResponse, type NextRequest } from 'next/server'

export async function proxy(request: NextRequest) {
    const pathname = request.nextUrl.pathname
    if (pathname === '/privacidad' || pathname === '/terminos' || pathname === '/auth/callback' || pathname.startsWith('/auth/callback/')) {
        return NextResponse.next()
    }

    let response = NextResponse.next({
        request: {
            headers: request.headers,
        },
    })

    const supabase = createServerClient(
        process.env.NEXT_PUBLIC_SUPABASE_URL!,
        process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
        {
            cookies: {
                get(name: string) {
                    return request.cookies.get(name)?.value
                },
                set(name: string, value: string, options: CookieOptions) {
                    request.cookies.set({
                        name,
                        value,
                        ...options,
                    })
                    response = NextResponse.next({
                        request: {
                            headers: request.headers,
                        },
                    })
                    response.cookies.set({
                        name,
                        value,
                        ...options,
                    })
                },
                remove(name: string, options: CookieOptions) {
                    request.cookies.set({
                        name,
                        value: '',
                        ...options,
                    })
                    response = NextResponse.next({
                        request: {
                            headers: request.headers,
                        },
                    })
                    response.cookies.set({
                        name,
                        value: '',
                        ...options,
                    })
                },
            },
        }
    )

    const {
        data: { user },
    } = await supabase.auth.getUser()

    console.log(`[Proxy] Path: ${request.nextUrl.pathname}, User: ${user ? user.email : 'None'}`)

    // Protect /admin and /dashboard routes
    const isProtectedPath = request.nextUrl.pathname.startsWith('/admin') || 
                            request.nextUrl.pathname.startsWith('/dashboard')
    
    if (isProtectedPath && !user) {
        console.log(`[Proxy] Redirecting to /login from ${request.nextUrl.pathname}`)
        return NextResponse.redirect(new URL('/login', request.url))
    }

    // Redirect authenticated users from /login
    if (request.nextUrl.pathname === '/login' && user) {
        console.log(`[Proxy] Authenticated user on /login, redirecting to /dashboard`)
        return NextResponse.redirect(new URL('/dashboard', request.url))
    }

    return response
}

export const config = {
    matcher: [
        /*
         * Match all request paths except for the ones starting with:
         * - _next/static (static files)
         * - _next/image (image optimization files)
         * - favicon.ico (favicon file)
         * Feel free to modify this pattern to include more paths.
         */
        '/((?!_next/static|_next/image|favicon.ico|.*\\.(?:svg|png|jpg|jpeg|gif|webp)$).*)',
    ],
}
